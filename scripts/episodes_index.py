def all_episodes() -> list:
    """Yield (episode_id, episode_html_url, source_class) tuples.

    For "direct" entries, the episode_html_url is derived from the date.
    For "scrape" entries, the third tuple element is the actual filename.
    """
    out = []
    BASE = "https://bhoot-fm.com/download/"
    for entry in EPISODES:
        if entry[1] == "direct":
            date, _ = entry[0], entry[1]
            out.append((date, BASE + f"Bhoot-FM_{date}.html", "direct"))
        else:
            date, _, fname = entry
            out.append((date, BASE + fname, "scrape"))
    return out


